def generate_candidate_paths(nodes, OD, dist_matrix, time_matrix, detour_factor, W_phy, dates):
    node_tonnage = defaultdict(float)
    for (o, d) in OD:
        total_p = sum(W_phy.get((o, d, dt), 0.0) for dt in dates)
        node_tonnage[o] += total_p
        node_tonnage[d] += total_p

    top_hubs = sorted(nodes, key=lambda n: node_tonnage[n], reverse=True)[:6]

    P_od = {}
    for (o, d) in OD:
        d_direct = dist_matrix[(o, d)]
        max_d = detour_factor.get((o, d), 1.5) * d_direct

        paths = [{
            "id": 0,
            "nodes": [o, d],
            "arcs": [(o, d)],
            "hops": [],
            "dist": d_direct,
            "transit_time": time_matrix[(o, d)],
            "handling_time": 0.0
        }]

        candidates = []
        for h in top_hubs:
            if h != o and h != d:
                d_total = dist_matrix[(o, h)] + dist_matrix[(h, d)]
                if d_total <= max_d:
                    candidates.append({
                        "nodes": [o, h, d],
                        "arcs": [(o, h), (h, d)],
                        "hops": [h],
                        "dist": d_total,
                        "transit_time": time_matrix[(o, h)] + time_matrix[(h, d)],
                        "handling_time": 2.0
                    })

        candidates.sort(key=lambda x: x["dist"])
        for idx, cand in enumerate(candidates[:2], start=1):
            cand["id"] = idx
            paths.append(cand)

        P_od[(o, d)] = paths
    return P_od

class FullHorizonALNSWarmStarter:
    def __init__(self, OD, dates, W_phy, P_od, dist_matrix):
        self.OD = OD
        self.dates = dates
        self.W_phy = W_phy
        self.P_od = P_od
        self.dist_matrix = dist_matrix
        self.W_phy_tot = sum(W_phy.values())

    def generate_warm_start(self, target_spill_pct=0.119):
        lane_density = {
            od: sum(self.W_phy.get((od[0], od[1], dt), 0.0) for dt in self.dates) / max(1.0, self.dist_matrix[od])
            for od in self.OD
        }
        sorted_lanes = sorted(self.OD, key=lambda od: lane_density[od])

        spillover_hints = {od: 0 for od in self.OD}
        path_hints = {od: 0 for od in self.OD}

        spill_target_kg = target_spill_pct * self.W_phy_tot
        current_spill = 0.0

        for od in sorted_lanes:
            tonnage = sum(self.W_phy.get((od[0], od[1], dt), 0.0) for dt in self.dates)
            if current_spill + tonnage <= spill_target_kg:
                spillover_hints[od] = 1
                current_spill += tonnage
            else:
                break

        for od in self.OD:
            if spillover_hints[od] == 0 and len(self.P_od[od]) > 1:
                lane_tonnage = sum(self.W_phy.get((od[0], od[1], dt), 0.0) for dt in self.dates)
                if lane_tonnage < 35000:
                    path_hints[od] = 1

        return {"spillover": spillover_hints, "path_selection": path_hints}

def solve_full_horizon_linehaul_cpsat(nodes, dates, OD, vehicle_types, dist_matrix, time_matrix,
                                      detour_factor, processing_cap, cpk, one_way_factor,
                                      W_phy, W_vol, P_od, warm_start_hints, time_limit_sec=2400):
    model = cp_model.CpModel()
    start_t = time.time()

    W_phy_tot = sum(W_phy.values())
    W_vol_tot = sum(W_vol.values())

    active_physical_arcs = set()
    for od in OD:
        for p in P_od[od]:
            for arc in p["arcs"]:
                active_physical_arcs.add(arc)
    active_physical_arcs = sorted(list(active_physical_arcs))

    theta = {}
    s = {}
    for od in OD:
        s[od] = model.NewBoolVar(f"spill_{od[0]}_{od[1]}")
        for p in P_od[od]:
            theta[(od, p["id"])] = model.NewBoolVar(f"th_{od[0]}_{od[1]}_{p['id']}")

    m = {k: model.NewIntVar(0, 350, f"m_{k}") for k in vehicle_types}

    y = {}
    for k in vehicle_types:
        for arc in active_physical_arcs:
            for dt in dates:
                y[(k, arc, dt)] = model.NewIntVar(0, 60, f"y_{k[:3]}_{arc[0]}_{arc[1]}_{dt[:2]}")

    if warm_start_hints:
        for od in OD:
            spill_val = warm_start_hints["spillover"].get(od, 0)
            model.AddHint(s[od], spill_val)
            cand_p = warm_start_hints["path_selection"].get(od, 0)
            for p in P_od[od]:
                model.AddHint(theta[(od, p["id"])], 1 if (p["id"] == cand_p and spill_val == 0) else 0)

    for od in OD:
        model.Add(sum(theta[(od, p["id"])] for p in P_od[od]) + s[od] == 1)

    spill_phy_terms = []
    spill_vol_terms = []
    for od in OD:
        w_p_lane = int(round(sum(W_phy.get((od[0], od[1], dt), 0.0) for dt in dates)))
        w_v_lane = int(round(sum(W_vol.get((od[0], od[1], dt), 0.0) for dt in dates)))
        spill_phy_terms.append(s[od] * w_p_lane)
        spill_vol_terms.append(s[od] * w_v_lane)

    max_phy_spill = int(math.floor(0.12 * W_phy_tot))
    max_vol_spill = int(math.floor(0.12 * W_vol_tot))
    model.Add(sum(spill_phy_terms) <= max_phy_spill)
    model.Add(sum(spill_vol_terms) <= max_vol_spill)

    for k in vehicle_types:
        for dt in dates:
            model.Add(sum(y[(k, arc, dt)] for arc in active_physical_arcs) <= m[k])

    arc_to_path_flows = defaultdict(list)
    for od in OD:
        for p in P_od[od]:
            for arc in p["arcs"]:
                arc_to_path_flows[arc].append((od, p["id"]))

    for arc in active_physical_arcs:
        for dt in dates:
            active_flows = [(od, p_id) for (od, p_id) in arc_to_path_flows[arc]
                            if W_phy.get((od[0], od[1], dt), 0.0) > 0 or W_vol.get((od[0], od[1], dt), 0.0) > 0]
            if not active_flows:
                continue

            model.Add(
                sum(y[(k, arc, dt)] * int(vehicle_types[k]["Q_phy"]) for k in vehicle_types) >=
                sum(theta[(od, p_id)] * int(round(W_phy.get((od[0], od[1], dt), 0.0))) for (od, p_id) in active_flows)
            )

            model.Add(
                sum(y[(k, arc, dt)] * int(vehicle_types[k]["Q_vol"]) for k in vehicle_types) >=
                sum(theta[(od, p_id)] * int(round(W_vol.get((od[0], od[1], dt), 0.0))) for (od, p_id) in active_flows)
            )

    objective_terms = []
    for (k, arc, dt), y_var in y.items():
        specs = vehicle_types[k]
        d_leg = dist_matrix[arc]
        ow_fact = one_way_factor.get(arc, 1.0)
        trip_cost = int(round((specs["F"] + specs["C_km"] * d_leg) * ow_fact))
        objective_terms.append(y_var * trip_cost)

    for od in OD:
        for p in P_od[od]:
            total_tonnage = sum(W_phy.get((od[0], od[1], dt), 0.0) for dt in dates)
            if p["hops"]:
                hop_cost_kg = sum(cpk.get(h, 0.45) for h in p["hops"])
                handling_cost = int(round(hop_cost_kg * total_tonnage))
                hop_penalty = int(round(0.20 * total_tonnage))
                objective_terms.append(theta[(od, p["id"])] * (handling_cost + hop_penalty))

    horizon_days = len(dates)
    for k in vehicle_types:
        f_regularizer = int(round(vehicle_types[k]["F"] * 0.10 * horizon_days))
        objective_terms.append(m[k] * f_regularizer)

    model.Minimize(sum(objective_terms))

    solver = cp_model.CpSolver()
    solver.parameters.max_time_in_seconds = float(time_limit_sec)
    solver.parameters.num_search_workers = 8
    solver.parameters.linearization_level = 2
    solver.parameters.cp_model_probing_level = 2
    solver.parameters.use_rins_lns = True
    solver.parameters.log_search_progress = False

    status = solver.Solve(model)
    elapsed = time.time() - start_t

    status_map = {
        cp_model.OPTIMAL: "OPTIMAL",
        cp_model.FEASIBLE: "FEASIBLE (Sub-optimal integer solution)",
        cp_model.INFEASIBLE: "INFEASIBLE",
        cp_model.MODEL_INVALID: "MODEL_INVALID",
        cp_model.UNKNOWN: "TIME_LIMIT / UNKNOWN"
    }
    status_str = status_map.get(status, "UNKNOWN")

    obj_val = solver.ObjectiveValue() if status in (cp_model.OPTIMAL, cp_model.FEASIBLE) else None
    best_bound = solver.BestObjectiveBound() if status in (cp_model.OPTIMAL, cp_model.FEASIBLE) else None

    if obj_val is not None and best_bound is not None and abs(obj_val) > 1e-4:
        gap_pct = abs((obj_val - best_bound) / obj_val) * 100.0
    elif status == cp_model.OPTIMAL:
        gap_pct = 0.0
    else:
        gap_pct = None

    stats = {
        "status": status_str,
        "runtime_sec": elapsed,
        "obj_val": obj_val,
        "best_bound": best_bound,
        "optimization_gap_pct": gap_pct,
        "branches": solver.NumBranches(),
        "conflicts": solver.NumConflicts(),
        "variables_count": len(model.Proto().variables),
        "constraints_count": len(model.Proto().constraints)
    }

    if status in (cp_model.OPTIMAL, cp_model.FEASIBLE):
        fleet_committed = {k: int(solver.Value(m[k])) for k in vehicle_types}
        stats["fleet_committed"] = fleet_committed

        total_fixed_cost = 0.0
        total_km_cost = 0.0
        total_hop_cost = 0.0

        for (k, arc, dt), y_var in y.items():
            trips = solver.Value(y_var)
            if trips > 0:
                specs = vehicle_types[k]
                d_leg = dist_matrix[arc]
                ow_fact = one_way_factor.get(arc, 1.0)
                total_fixed_cost += (specs["F"] * trips) * ow_fact
                total_km_cost += (specs["C_km"] * d_leg * trips) * ow_fact

        total_spilled_phy = 0.0
        total_spilled_vol = 0.0
        load_weighted_hops = 0.0
        load_weighted_dist = 0.0
        served_phy = 0.0

        path_selection = {}
        spillover = {}

        for od in OD:
            is_spilled = (solver.Value(s[od]) == 1)
            spillover[od] = 1.0 if is_spilled else 0.0

            selected_pid = 0
            for p in P_od[od]:
                if solver.Value(theta[(od, p["id"])]) == 1:
                    selected_pid = p["id"]
                    break
            path_selection[od] = selected_pid

            lane_phy = sum(W_phy.get((od[0], od[1], dt), 0.0) for dt in dates)
            lane_vol = sum(W_vol.get((od[0], od[1], dt), 0.0) for dt in dates)

            if is_spilled:
                total_spilled_phy += lane_phy
                total_spilled_vol += lane_vol
            else:
                served_phy += lane_phy
                p_sel = P_od[od][selected_pid]
                load_weighted_hops += len(p_sel["hops"]) * lane_phy
                load_weighted_dist += p_sel["dist"] * lane_phy
                for h in p_sel["hops"]:
                    total_hop_cost += cpk.get(h, 0.45) * lane_phy

        stats["fixed_cost"] = total_fixed_cost
        stats["km_cost"] = total_km_cost
        stats["hop_cost"] = total_hop_cost
        stats["linehaul_cost"] = total_fixed_cost + total_km_cost
        stats["total_cost_incurred"] = total_fixed_cost + total_km_cost + total_hop_cost

        stats["total_weight_phy"] = W_phy_tot
        stats["total_weight_vol"] = W_vol_tot
        stats["spilled_phy_kg"] = total_spilled_phy
        stats["spilled_vol_kg"] = total_spilled_vol
        stats["spill_pct_phy"] = (total_spilled_phy / max(1.0, W_phy_tot)) * 100.0
        stats["spill_pct_vol"] = (total_spilled_vol / max(1.0, W_vol_tot)) * 100.0

        stats["avg_hops"] = load_weighted_hops / max(1.0, served_phy)
        stats["avg_dist"] = load_weighted_dist / max(1.0, served_phy)

        stats["solution"] = {"path_selection": path_selection, "spillover": spillover}
    else:
        stats["solution"] = {"path_selection": {od: 0 for od in OD}, "spillover": {od: 0.0 for od in OD}}

    return stats

def generate_deliverables(solution, nodes, dates, OD, vehicle_types,
                          dist_matrix, time_matrix, detour_factor, processing_cap,
                          cpk, one_way_factor, W_phy, W_vol, num_shipments, P_od, output_dir="reports_output"):
    os.makedirs(output_dir, exist_ok=True)
    path_sel = solution["path_selection"]
    spill = solution["spillover"]

    multi_32ft, single_32ft = get_resolved_32ft_types(vehicle_types)

    order_rows = []
    hop_rows = []
    order_id = 1

    for od in OD:
        o, d = od
        pid = path_sel.get(od, 0)
        p = P_od[od][pid]
        is_spilled = spill.get(od, 0.0) > 0.95
        d_direct = dist_matrix[(o, d)]
        t_direct = time_matrix[(o, d)]
        d_actual = p["dist"]
        t_actual = p["transit_time"]
        detour_ratio = round(d_actual / max(1.0, d_direct), 2)
        detour_limit = detour_factor.get(od, 1.5)
        detour_pass = "PASS" if d_actual <= detour_limit * d_direct + 1e-3 else "FAIL"
        stop_pass = "PASS" if len(p["hops"]) <= 4 else "FAIL"

        for dt in dates:
            w_p = W_phy.get((o, d, dt), 0.0)
            w_v = W_vol.get((o, d, dt), 0.0)
            if w_p <= 0.0 and w_v <= 0.0:
                continue

            n_ship = num_shipments.get((o, d, dt), 1)
            h_cost = sum(cpk.get(h, 0.45) * w_p for h in p["hops"]) if not is_spilled else 0.0

            route_str = " -> ".join(p["nodes"])
            order_rows.append({
                "order_id": f"ORD_{order_id:06d}",
                "date": dt,
                "origin": o,
                "destination": d,
                "physical_weight_kg": w_p,
                "volumetric_weight_kg": w_v,
                "shipment_count": n_ship,
                "status": "UNSERVED" if is_spilled else "SERVED",
                "route_sequence": route_str,
                "legs_count": len(p["arcs"]),
                "transshipment_stops_count": len(p["hops"]),
                "intermediate_hubs": ",".join(p["hops"]) if p["hops"] else "NONE",
                "direct_distance_km": d_direct,
                "actual_distance_km": d_actual,
                "detour_ratio": detour_ratio,
                "detour_factor_cap": detour_limit,
                "detour_compliance": detour_pass,
                "stop_limit_compliance": stop_pass,
                "direct_time_hrs": t_direct,
                "actual_transit_time_hrs": t_actual,
                "handling_time_hrs": p["handling_time"],
                "total_elapsed_time_hrs": t_actual + p["handling_time"],
                "order_handling_cost": round(h_cost, 2),
                "apportioned_linehaul_cost": round(d_actual * 31.0 * (w_p / 14000.0), 2)
            })

            hop_rows.append({
                "order_id": f"ORD_{order_id:06d}",
                "date": dt,
                "origin": o,
                "destination": d,
                "weight_kg": w_p,
                "transfer_hops_count": len(p["hops"]),
                "transfer_hub_sequence": " -> ".join(p["nodes"])
            })
            order_id += 1

    df_71 = pd.DataFrame(order_rows)
    df_72 = pd.DataFrame(hop_rows)
    df_71.to_csv(os.path.join(output_dir, "7.1_order_level_routing_report.csv"), index=False)
    df_72.to_csv(os.path.join(output_dir, "7.2_hop_view_order_report.csv"), index=False)

    alloc_rows = []
    for od in OD[:150]:
        pid = path_sel.get(od, 0)
