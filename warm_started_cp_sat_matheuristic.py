def get_resolved_32ft_types(vehicle_types):
    multi_axle = None
    single_axle = None
    for k in vehicle_types.keys():
        k_lower = k.lower().strip()
        if "32 ft" in k_lower or "32ft" in k_lower:
            if "multi" in k_lower:
                multi_axle = k
            elif "single" in k_lower or "9-mt" in k_lower or "axel" in k_lower or "axle" in k_lower:
                single_axle = k

    all_keys = list(vehicle_types.keys())
    if not multi_axle:
        multi_axle = all_keys[0]
    if not single_axle:
        single_axle = all_keys[1] if len(all_keys) > 1 else multi_axle

    return multi_axle, single_axle

